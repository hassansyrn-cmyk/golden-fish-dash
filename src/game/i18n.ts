const listeners = new Set<(language: AppLanguage) => void>();

export function detectDeviceLanguage(): AppLanguage {
  if (typeof navigator === 'undefined') return 'en';
  const candidate = navigator.languages?.[0] ?? navigator.language ?? 'en';
  return candidate.toLowerCase().startsWith('ar') ? 'ar' : 'en';
}

export function applyLanguageToDocument(language: AppLanguage) {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
}

export function getAppLanguage(): AppLanguage {
  return getSettings().language ?? detectDeviceLanguage();
}

export function initializeLanguage(): AppLanguage {
  const language = getAppLanguage();
  applyLanguageToDocument(language);
  return language;
}

export function changeLanguage(language: AppLanguage) {
  persistLanguage(language);
  applyLanguageToDocument(language);
  listeners.forEach((listener) => listener(language));
}

export function translate(key: string, language = getAppLanguage(), params: TranslationParams = {}): string {
  const template = translations[language][key] ?? translations.en[key] ?? key;
  return template.replace(/{{(\w+)}}/g, (_, param: string) => String(params[param] ?? `{{${param}}}`));
}

export function translateSkin(id: string, field: 'name' | 'ability', language = getAppLanguage()) {
  return translate(`skin.${id}.${field}`, language);
}

export function translateMission(id: string, language = getAppLanguage()) {
  return translate(`mission.${id}`, language);
}

export function translateDailyRewardCard(day: number, language = getAppLanguage()) {
  return translate(`rewardCard.${day}`, language);
}

export function translateAchievement(id: string, field: 'name' | 'description', language = getAppLanguage()) {
  return translate(`achievement.${id}.${field}`, language);
}

export function translateDailyChallenge(id: string, language = getAppLanguage()) {
  return translate(`daily.${id}`, language);
}

export function useI18n() {
  const [language, setLanguage] = useState<AppLanguage>(() => initializeLanguage());

  useEffect(() => {
    const listener = (nextLanguage: AppLanguage) => setLanguage(nextLanguage);
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, []);

  return useMemo(() => ({
    language,
    isArabic: language === 'ar',
    t: (key: string, params?: TranslationParams) => translate(key, language, params),
    setLanguage: changeLanguage,
  }), [language]);
}
